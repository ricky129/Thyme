#!/usr/bin/env bash
# Generates a compact map of the Java sources: types and non-private method signatures.
# Usage: ./bin/codemap.sh > docs/codemap.md
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

decl='^[[:space:]]*(public |protected |private |static |final |abstract |sealed )*(class|interface|record|enum) [A-Z]'
meth='^    ((public|protected|private|static|final|synchronized|abstract|default) )*[A-Za-z][][A-Za-z0-9_<>,.? ]* [a-z][A-Za-z0-9_]*\('

echo "# Code map"
echo
echo "Generated by bin/codemap.sh: do not edit. Types and non-private method signatures of main code."
echo
files=$(git ls-files -co --exclude-standard '*.java' | sort)
for f in $files; do
    case "$f" in */src/test/*) continue ;; esac
    echo "## $f ($(wc -l < "$f") lines)"
    grep -nE "$decl|$meth" "$f" \
        | grep -vE '^[0-9]+: +private ' \
        | sed -E 's/[[:space:]]+/ /g; s/ ?\{$//' | cut -c1-150 || true
    echo
done
echo "## Tests"
for f in $files; do
    case "$f" in */src/test/*) echo "- $f ($(wc -l < "$f") lines)" ;; esac
done
